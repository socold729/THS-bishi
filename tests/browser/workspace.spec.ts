const blocked = { style: "short", date: "2026-10-27", latestClosedDate: null, fetchedAt: "2026-10-27T09:00:00Z", status: "blocked", metrics: [], indices: [], limitCounts: [], bars: [], indicatorsComplete: false, stocks: [], ladder: [], coverage: [], evidence: [], messages: ["测试模拟：数据认证失败，未取得市场数据。"], ai: { status: "not_implemented", message: "AI报告待接入。" } };

