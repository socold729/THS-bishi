test("strategy routes actually return different provider datasets", async ({ request }) => {
  // Two sequential live-provider requests; value mode now has a 50-second data budget.
  test.setTimeout(120000);
  const swingResponse = await request.get("/api/dashboard?style=swing&symbols=600519.SH");
  expect(swingResponse.status()).toBe(200);
  const swing = await swingResponse.json();
  expect(swing.evidence.some((e: { endpoint: string }) => e.endpoint === "/api/a-share/prices/historical"), JSON.stringify(swing.coverage)).toBe(true);
  expect(swing.metrics.some((m: { id: string }) => m.id === "ma60")).toBe(true);
  const valueResponse = await request.get("/api/dashboard?style=value&symbols=600519.SH");
  const value = await valueResponse.json();
  expect(value.evidence.some((e: { endpoint: string }) => e.endpoint === "/api/a-share/financials/income-statements"), JSON.stringify(value.coverage)).toBe(true);
  expect(value.limitCounts).toHaveLength(2);
  expect(value.limitCounts.every((m:{value:number|null})=>m.value!==null),JSON.stringify(value.coverage)).toBe(true);
  expect(value.indices.every((i:{close:number|null})=>i.close!==null),JSON.stringify(value.coverage)).toBe(true);
  expect(value.indices.map((index: { code: string }) => index.code)).toEqual(["000001.SH", "399001.SZ", "399006.SZ", "000680.SH"]);
  expect(value.evidence.some((e: { endpoint: string }) => e.endpoint === "/api/a-share/special-data/limit-up-ladder")).toBe(false);
  expect(value.ai.status).toBe("available");
});
